//! The Jellyfin Merge Proxy Grafana dashboard, generated into
//! deploy/grafana-dashboard.json by `cargo xtask dashboard`.
//!
//! Layout (top to bottom): health at a glance, client traffic (RED),
//! upstream servers, request pipeline, streaming, merge/dedupe, catalog cache,
//! clients & auth, configuration & TLS, process. Rate panels use
//! `$__rate_interval`; "(range)" panels summarise the selected time range.

use crate::grafana::{color_by_name, ds, map_value, palette, q, steps, Layout, Panel};
use serde_json::{json, Value};

// Label filters shared by every query.
const I: &str = r#"instance=~"$instance""#;
const IS: &str = r#"instance=~"$instance", server=~"$server""#;

// One palette for the whole board.
const GOOD: &str = "green";
const WARN: &str = "orange";
const BAD: &str = "red";
const INFO: &str = "blue";
const NEUTRAL: &str = "text";
const ACCENT: &str = "purple";

fn rate(metric: &str, sel: &str) -> String {
    format!("rate({metric}{{{sel}}}[$__rate_interval])")
}

fn quantile(qn: f64, metric: &str, sel: &str, by: &str) -> String {
    let by = if by.is_empty() {
        "le".to_string()
    } else {
        format!("{by}, le")
    };
    format!(
        "histogram_quantile({qn}, sum by ({by}) ({}))",
        rate(&format!("{metric}_bucket"), sel)
    )
}

fn status_palette() -> Vec<Value> {
    palette(&[("2xx", GOOD), ("3xx", INFO), ("4xx", WARN), ("5xx", BAD)])
}

pub fn build() -> Value {
    let mut l = Layout::new();
    overview(&mut l);
    traffic(&mut l);
    upstreams(&mut l);
    pipeline(&mut l);
    streaming(&mut l);
    merge(&mut l);
    cache(&mut l);
    auth(&mut l);
    config_tls(&mut l);
    process(&mut l);

    json!({
        "title": "Jellyfin Merge Proxy",
        "uid": "jellyfin-merge-proxy",
        "description": "Client traffic, upstream health, streaming, merge/dedupe, cache, auth, config/TLS and process metrics for jellyfin-merge-proxy. Generated by `cargo xtask dashboard`; see METRICS.md.",
        "tags": ["jellyfin", "jellyfin-merge-proxy", "proxy"],
        "editable": true,
        "graphTooltip": 1,
        "fiscalYearStartMonth": 0,
        "liveNow": false,
        "refresh": "30s",
        "schemaVersion": 39,
        "version": 1,
        "time": {"from": "now-3h", "to": "now"},
        "timepicker": {"refresh_intervals": ["10s", "30s", "1m", "5m", "15m", "1h"]},
        "timezone": "browser",
        "weekStart": "",
        "links": [{
            "title": "Metric reference",
            "type": "link",
            "icon": "doc",
            "tooltip": "METRICS.md: every metric and label",
            "url": "https://github.com/Quyzi/jellyfin-merge-proxy/blob/master/METRICS.md",
            "targetBlank": true,
            "asDropdown": false, "includeVars": false, "keepTime": false, "tags": []
        }],
        "annotations": {"list": annotations()},
        "templating": {"list": variables()},
        "panels": l.panels,
    })
}

