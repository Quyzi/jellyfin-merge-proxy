fn annotations() -> Vec<Value> {
    let ann = |name: &str, color: &str, expr: String, title: &str| {
        json!({
            "name": name, "datasource": ds(), "enable": true, "hide": false, "iconColor": color,
            "expr": expr, "step": "30s", "titleFormat": title, "textFormat": "", "tagKeys": "",
            "useValueForTime": false
        })
    };
    vec![
        json!({
            "builtIn": 1, "datasource": {"type": "grafana", "uid": "-- Grafana --"},
            "enable": true, "hide": true, "iconColor": "rgba(0, 211, 255, 1)",
            "name": "Annotations & Alerts", "type": "dashboard"
        }),
        ann(
            "Config reloads",
            "blue",
            format!("changes(jmp_config_generation{{{I}}}[1m]) > 0"),
            "Config applied",
        ),
        ann(
            "TLS reloads",
            "purple",
            format!("sum by (target) (increase(jmp_tls_reloads_total{{{I}}}[1m])) > 0"),
            "TLS {{target}} reloaded",
        ),
    ]
}
